// Shared helpers for scripts/ops (run with `npx tsx@4.23.15`). NEVER print secret values.
import { existsSync, readFileSync, writeFileSync, chmodSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const REPO = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const ENV_LOCAL = join(REPO, "apps", "web", ".env.local");
export const SPIKES_ENV = process.env.SOLSEND_SPIKES_ENV ?? "/Users/darrendeepak/solsend/spikes/.env";
export const KEYS_DIR = (process.env.SOLSEND_KEYS_DIR ?? "~/.config/solsend/devnet").replace(/^~(?=\/)/, homedir());
export const LITHIC_SANDBOX = "https://sandbox.lithic.com";

/** Minimal dotenv parser (KEY=VALUE, optional quotes, # comments). Values stay in memory. */
export function parseEnvFile(path: string): Map<string, string> {
  const out = new Map<string, string>();
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/.exec(line);
    if (!m) continue;
    let v = m[2]!;
    if ((v.startsWith('"') && v.endsWith('"')) || (v.startsWith("'") && v.endsWith("'"))) v = v.slice(1, -1);
    else v = v.replace(/\s+#.*$/, "");
    out.set(m[1]!, v);
  }
  return out;
}

/** Merge `updates` into apps/web/.env.local (mode 600). Returns the names written. Never logs values. */
export function writeEnvLocal(updates: Map<string, string>): string[] {
  const cur = parseEnvFile(ENV_LOCAL);
  for (const [k, v] of updates) cur.set(k, v);
  const body = ["# Generated by scripts/ops (devnet + Lithic SANDBOX). NEVER commit. Mode 600.", ...[...cur].map(([k, v]) => `${k}=${/[\s#"']/.test(v) ? JSON.stringify(v) : v}`)].join("\n") + "\n";
  writeFileSync(ENV_LOCAL, body, { mode: 0o600 });
  chmodSync(ENV_LOCAL, 0o600);
  return [...updates.keys()];
}

/** Replace-or-append one KEY=VALUE line in an existing env file, preserving every other line; mode 600. */
export function upsertEnvFile(path: string, key: string, value: string): void {
  const lines = existsSync(path) ? readFileSync(path, "utf8").split(/\r?\n/) : [];
  const re = new RegExp(`^\\s*(?:export\\s+)?${key}\\s*=`);
  const idx = lines.findIndex((l) => re.test(l));
  if (idx >= 0) lines[idx] = `${key}=${value}`;
  else { if (lines.length && lines[lines.length - 1] === "") lines.pop(); lines.push(`${key}=${value}`, ""); }
  writeFileSync(path, lines.join("\n"), { mode: 0o600 });
  chmodSync(path, 0o600);
}

export const readKeyfile =(name: string): string => {
  const raw = readFileSync(join(KEYS_DIR, `${name}.json`), "utf8").trim();
  const arr = JSON.parse(raw) as number[];
  if (!Array.isArray(arr) || arr.length !== 64) throw new Error(`${name}.json is not a 64-byte keypair`);
  return JSON.stringify(arr);
};

/** Load app env: apps/web/.env.local overlaid on spikes/.env (in-process only). */
export function appEnv(): Map<string, string> {
  const m = parseEnvFile(SPIKES_ENV);
  for (const [k, v] of parseEnvFile(ENV_LOCAL)) m.set(k, v);
  return m;
}

let lithicCalls = 0;
const MAX_LITHIC_CALLS = Number(process.env.LITHIC_MAX_CALLS_PER_RUN ?? 12);
/** Lithic SANDBOX call with a per-run cap and write pacing. Returns status + parsed JSON (never printed raw). */
export async function lithic(apiKey: string, method: "GET" | "POST" | "PATCH" | "DELETE", path: string, body?: unknown): Promise<{ status: number; json: any }> {
  if (++lithicCalls > MAX_LITHIC_CALLS) throw new Error(`refusing: > ${MAX_LITHIC_CALLS} Lithic sandbox calls in one run`);
  if (method !== "GET") await new Promise((r) => setTimeout(r, 600));
  const res = await fetch(`${LITHIC_SANDBOX}${path}`, {
    method, headers: { Authorization: apiKey, "content-type": "application/json", accept: "application/json" }, body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  let json: any = {};
  try { json = text ? JSON.parse(text) : {}; } catch { json = {}; }
  return { status: res.status, json };
}
export const lithicCallsUsed = () => lithicCalls;

/** Evidence-safe RPC label (QuickNode URLs embed a token). */
export function rpcLabel(url: string): string {
  try {
    const h = new URL(url).host;
    if (h === "api.devnet.solana.com") return "public devnet";
    return /quiknode/i.test(h) ? "quicknode devnet (endpoint redacted)" : "custom devnet RPC (redacted)";
  } catch { return "invalid"; }
}
