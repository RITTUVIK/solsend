// Generates infra/quicknode/filter.dist.js from packages/shared/idl/solsend.json so the QuickNode filter
// can never drift from the program's event layouts. Usage: tsx infra/quicknode/build-filter.ts
// The emitted file is plain ES2020 for QuickNode's sandbox (no require/import/network), entry point `main`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const IDL_PATH = join(HERE, "../../packages/shared/idl/solsend.json");
export const FILTER_DIST = join(HERE, "filter.dist.js");

type IdlType = string | { array: [IdlType, number] } | { defined: { name: string } };
type Field = { name: string; type: IdlType };
const camel = (s: string) => s.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** Field decoder codes understood by the emitted filter. */
type Code = "pubkey" | "u64" | "i64" | "u8" | "u16" | "u32" | "bool" | "hex32";

function code(t: IdlType, where: string): Code {
  if (typeof t === "string") {
    if (["pubkey", "u64", "i64", "u8", "u16", "u32", "bool"].includes(t)) return t as Code;
  } else if ("array" in t && t.array[0] === "u8" && t.array[1] === 32) return "hex32";
  throw new Error(`build-filter: unsupported event field type ${JSON.stringify(t)} at ${where}`);
}

export function buildFilterSource(): string {
  const idl = JSON.parse(readFileSync(IDL_PATH, "utf8")) as {
    address: string;
    events: { name: string; discriminator: number[] }[];
    types: { name: string; type: { fields?: Field[] } }[];
  };
  const table: Record<string, { name: string; fields: [string, Code][] }> = {};
  for (const ev of idl.events) {
    const def = idl.types.find((t) => t.name === ev.name);
    if (!def?.type.fields) throw new Error(`build-filter: no struct for event ${ev.name}`);
    table[ev.discriminator.join(",")] = { name: ev.name, fields: def.type.fields.map((f) => [camel(f.name), code(f.type, `${ev.name}.${f.name}`)] as [string, Code]) };
  }
  return TEMPLATE.replace("__PROGRAM__", JSON.stringify(idl.address)).replace("__EVENTS__", JSON.stringify(table, null, 1));
}

const TEMPLATE = `// GENERATED by infra/quicknode/build-filter.ts from packages/shared/idl/solsend.json - DO NOT EDIT.
// QuickNode Streams filter: Solana devnet, dataset "programs_with_logs". Runs in QuickNode's sandbox.
// Input : stream.data = [[ { signature, slot, blockTime, success, logs[], programInvocations[] } ]]
//         (programInvocations = top-level instructions only, instruction.data is base58)
// Output: QnPayload v1 { solsend: "v1", matches: [ { signature, slot, blockTime, success, events[] } ] }
// No memo: settle txs carry none (the Lithic token is never published onchain; link via event authHash).
// Events are decoded ONLY from "Program data:" lines emitted while the SolSend program is the executing program
// (tracked with the invoke stack), so a decoy data line from a CPI callee is ignored.
const OUR_PROGRAM = __PROGRAM__;
const EVENTS = __EVENTS__;

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
function b64decode(s) {
  const clean = s.replace(/[^A-Za-z0-9+/]/g, "");
  const out = [];
  let buf = 0, bits = 0;
  for (const ch of clean) {
    buf = ((buf << 6) | B64.indexOf(ch)) & 0xffffff;
    bits += 6;
    if (bits >= 8) { bits -= 8; out.push((buf >> bits) & 0xff); }
  }
  return out;
}

const B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";
function b58encode(bytes) {
  const digits = [0];
  for (const byte of bytes) {
    let carry = byte;
    for (let i = 0; i < digits.length; i++) { carry += digits[i] << 8; digits[i] = carry % 58; carry = (carry / 58) | 0; }
    while (carry > 0) { digits.push(carry % 58); carry = (carry / 58) | 0; }
  }
  let s = "";
  for (let k = 0; k < bytes.length && bytes[k] === 0; k++) s += "1";
  for (let i = digits.length - 1; i >= 0; i--) s += B58[digits[i]];
  return s;
}
function uN(b, o, n) {
  let v = 0n;
  for (let i = n - 1; i >= 0; i--) v = (v << 8n) | BigInt(b[o + i]);
  return v;
}
const hex = (b) => b.map((x) => x.toString(16).padStart(2, "0")).join("");

function decodeEvent(bytes) {
  const def = EVENTS[bytes.slice(0, 8).join(",")];
  if (!def) return null;
  const ev = { name: def.name };
  let o = 8;
  for (const [name, kind] of def.fields) {
    if (kind === "pubkey") { ev[name] = b58encode(bytes.slice(o, o + 32)); o += 32; }
    else if (kind === "hex32") { ev[name] = hex(bytes.slice(o, o + 32)); o += 32; }
    else if (kind === "u64") { ev[name] = uN(bytes, o, 8).toString(); o += 8; }
    else if (kind === "i64") { const u = uN(bytes, o, 8); ev[name] = (u >= 1n << 63n ? u - (1n << 64n) : u).toString(); o += 8; }
    else if (kind === "u8") { ev[name] = bytes[o]; o += 1; }
    else if (kind === "u16") { ev[name] = Number(uN(bytes, o, 2)); o += 2; }
    else if (kind === "u32") { ev[name] = Number(uN(bytes, o, 4)); o += 4; }
    else if (kind === "bool") { ev[name] = bytes[o] !== 0; o += 1; }
  }
  return ev;
}

function decodeTx(tx) {
  const stack = [];
  const events = [];
  for (const line of tx.logs || []) {
    const inv = /^Program (\\w+) invoke \\[\\d+\\]/.exec(line);
    if (inv) { stack.push(inv[1]); continue; }
    if (/^Program \\w+ (success|failed)/.test(line)) { stack.pop(); continue; }
    if (stack[stack.length - 1] !== OUR_PROGRAM || !line.startsWith("Program data: ")) continue;
    const ev = decodeEvent(b64decode(line.slice(14)));
    if (ev) events.push(ev);
  }
  return {
    signature: tx.signature,
    slot: tx.slot,
    blockTime: tx.blockTime === undefined ? null : tx.blockTime,
    success: tx.success !== false,
    events,
  };
}

function main(stream) {
  const matches = [];
  for (const item of (stream && stream.data) || []) {
    for (const tx of Array.isArray(item) ? item : []) {
      if ((tx.programInvocations || []).some((i) => i.programId === OUR_PROGRAM)) matches.push(decodeTx(tx));
    }
  }
  if (!matches.length) return null;
  return { solsend: "v1", matches };
}
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(FILTER_DIST, buildFilterSource());
  console.log(`wrote ${FILTER_DIST}`);
}
